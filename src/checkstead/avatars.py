"""Profile pictures from the identity provider.

A picture is fetched once, at sign-in, while the provider credential is still
in hand. The server checks it and keeps the bytes, and the browser loads it
from this server only: the page never contacts a provider, and the image
policy stays ``img-src 'self'``. Any failure means no picture, never a failed
sign-in.
"""

from __future__ import annotations

import base64
import binascii
import hashlib
import urllib.parse
import urllib.request
from dataclasses import dataclass

from checkstead.http import USER_AGENT, build_opener, ensure_allowed

# A 96-pixel photo is a few kilobytes. Anything near this is not a photo.
MAX_BYTES = 256 * 1024
SIZE = 96

# Raster formats only. SVG can carry script, so it is never accepted.
_SIGNATURES = (
    (b"\x89PNG\r\n\x1a\n", "image/png"),
    (b"\xff\xd8\xff", "image/jpeg"),
    (b"GIF87a", "image/gif"),
    (b"GIF89a", "image/gif"),
)


@dataclass(frozen=True)
class Avatar:
    mime: str
    data: bytes

    @property
    def etag(self) -> str:
        return hashlib.sha256(self.data).hexdigest()[:16]


def sniff(data: bytes) -> str | None:
    """Media type from the file's own bytes; the provider's header is not trusted."""
    for signature, mime in _SIGNATURES:
        if data.startswith(signature):
            return mime
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "image/webp"
    return None


def from_bytes(data: bytes) -> Avatar | None:
    if not data or len(data) > MAX_BYTES:
        return None
    mime = sniff(data)
    return Avatar(mime, data) if mime else None


def _get(url: str, headers: dict[str, str], accept: str) -> bytes | None:
    try:
        ensure_allowed(url)
        request = urllib.request.Request(
            url, headers={**headers, "User-Agent": USER_AGENT, "Accept": accept}
        )
        with build_opener().open(request, timeout=10) as response:
            ensure_allowed(response.geturl())
            data = response.read(MAX_BYTES + 1)
    except Exception:
        return None
    return data if len(data) <= MAX_BYTES else None


def fetch(url: str, headers: dict[str, str] | None = None) -> Avatar | None:
    data = _get(url, headers or {}, "image/png, image/jpeg, image/gif, image/webp")
    return from_bytes(data) if data is not None else None


def sized(url: str) -> str:
    """GitHub avatar URL at the size the page shows (``s=96``)."""
    parts = urllib.parse.urlsplit(url)
    query = [(k, v) for k, v in urllib.parse.parse_qsl(parts.query) if k != "s"]
    query.append(("s", str(SIZE)))
    return urllib.parse.urlunsplit(parts._replace(query=urllib.parse.urlencode(query)))


def from_azure_payload(payload: object) -> Avatar | None:
    """Azure DevOps profile avatar: JSON with the image as base64 in ``value``.

    ``isAutoGenerated`` is Azure's own initials picture. The page draws
    initials itself, so that one is not kept.
    """
    if not isinstance(payload, dict) or payload.get("isAutoGenerated") is True:
        return None
    value = payload.get("value")
    if not isinstance(value, str) or len(value) > MAX_BYTES * 2:
        return None
    try:
        data = base64.b64decode(value, validate=True)
    except (binascii.Error, ValueError):
        return None
    return from_bytes(data)

